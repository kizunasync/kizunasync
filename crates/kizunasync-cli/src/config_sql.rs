    /// Rows a table held before its triggers existed have no changelog entry,
    /// so the seed runs once both triggers are attached.
    #[test]
    fn the_seed_follows_both_triggers_and_precedes_the_ledger_rows() {
        let sql = table_provision_sql("notes", &table("pull-only"));
        let delete_trigger = sql
            .find("for each row execute function kizunasync.track_delete();")
            .unwrap();
        let seed = sql
            .find("select kizunasync._seed_changelog('notes');")
            .unwrap();
        let ledger = sql.find("insert into kizunasync._provisions").unwrap();

        assert!(delete_trigger < seed);
        assert!(seed < ledger);
    }

